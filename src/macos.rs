#[derive(Clone, Debug, PartialEq)]
pub enum Hotkey {
    /// Tap (press + release with no other key in between) of a single modifier, by virtual keycode.
    ModifierTap {
        keycode: u16,
        flag: NSEventModifierFlags,
    },
    Chord {
        mods: NSEventModifierFlags,
        keycode: u16,
    },
}

/// "RightOption" | "RightCommand" | "LeftOption" | "Ctrl+Alt+Space" | "Cmd+Shift+D" | "F5"
/// Modifier keys that can be tapped alone as a hotkey: (name, virtual keycode, flag).
const MOD_TAPS: [(&str, u16, NSEventModifierFlags); 8] = [
    ("RightOption", 61, NSEventModifierFlags::Option),
    ("LeftOption", 58, NSEventModifierFlags::Option),
    ("RightCommand", 54, NSEventModifierFlags::Command),
    ("LeftCommand", 55, NSEventModifierFlags::Command),
    ("RightControl", 62, NSEventModifierFlags::Control),
    ("LeftControl", 59, NSEventModifierFlags::Control),
    ("RightShift", 60, NSEventModifierFlags::Shift),
    ("LeftShift", 56, NSEventModifierFlags::Shift),
];
/// The modifiers a hotkey can use. F-keys and arrows also carry Function/NumericPad flags, which must be ignored.
const MODS: NSEventModifierFlags = NSEventModifierFlags::Control
    .union(NSEventModifierFlags::Option)
    .union(NSEventModifierFlags::Shift)
    .union(NSEventModifierFlags::Command);
const LETTERS: &str = "asdfhgzxcv_bqweryt123465=97-80]ou[ip_lj'k;\\,/nm.";
const NAMED: [(&str, u16); 25] = [
    ("Space", 49),
    ("Return", 36),
    ("Tab", 48),
    ("Esc", 53),
    ("`", 50),
    ("F1", 122),
    ("F2", 120),
    ("F3", 99),
    ("F4", 118),
    ("F5", 96),
    ("F6", 97),
    ("F7", 98),
    ("F8", 100),
    ("F9", 101),
    ("F10", 109),
    ("F11", 103),
    ("F12", 111),
    ("F13", 105),
    ("F14", 107),
    ("F15", 113),
    ("F16", 106),
    ("F17", 64),
    ("F18", 79),
    ("F19", 80),
    ("F20", 90),
];

pub fn parse_hotkey(s: &str) -> Option<Hotkey> {
    if let Some(&(_, keycode, flag)) = MOD_TAPS.iter().find(|m| m.0 == s.trim()) {
        return Some(Hotkey::ModifierTap { keycode, flag });
    }
    let mut mods = NSEventModifierFlags::empty();
    let mut key = None;
    for part in s.split('+').map(str::trim) {
        match part.to_ascii_lowercase().as_str() {
            "ctrl" | "control" => mods |= NSEventModifierFlags::Control,
            "alt" | "option" | "opt" => mods |= NSEventModifierFlags::Option,
            "cmd" | "command" => mods |= NSEventModifierFlags::Command,
            "shift" => mods |= NSEventModifierFlags::Shift,
            k => key = keycode(k),
        }
    }
    key.map(|keycode| Hotkey::Chord { mods, keycode })
}
fn keycode(name: &str) -> Option<u16> {
    if name == "enter" {
        return Some(36);
    }
    if let Some(&(_, c)) = NAMED.iter().find(|n| n.0.eq_ignore_ascii_case(name)) {
        return Some(c);
    }
    let mut it = name.chars();
    match (it.next(), it.next()) {
        (Some(c), None) if c != '_' => LETTERS.find(c).map(|i| i as u16),
        _ => None,
    }
}
fn key_name(code: u16) -> Option<String> {
    if let Some(&(n, _)) = NAMED.iter().find(|n| n.1 == code) {
        return Some(n.into());
    }
    LETTERS
        .chars()
        .nth(code as usize)
        .filter(|&c| c != '_')
        .map(|c| c.to_ascii_uppercase().to_string())
}
/// Settings string for a key press, e.g. "Ctrl+Alt+Space". Plain keys need a modifier (except F-keys) so typing isn't hijacked.
fn chord_name(code: u16, flags: NSEventModifierFlags) -> Option<String> {
    let key = key_name(code)?;
    let mut out = String::new();
    for (f, n) in [
        (NSEventModifierFlags::Control, "Ctrl+"),
        (NSEventModifierFlags::Option, "Alt+"),
        (NSEventModifierFlags::Shift, "Shift+"),
        (NSEventModifierFlags::Command, "Cmd+"),
    ] {
        if flags.contains(f) {
            out.push_str(n);
        }
    }
    let fkey = key.len() > 1 && key.starts_with('F');
    (!out.is_empty() || fkey).then(|| out + &key)
}

/// Call `f` when Esc (no modifiers) is pressed in this app. Needed because a focused egui TextEdit
/// never sees Esc: AppKit's text input turns it into cancelOperation: first.
pub fn on_local_esc(f: impl Fn() + 'static) -> Option<Retained<objc2::runtime::AnyObject>> {
    let block = RcBlock::new(move |ev: NonNull<NSEvent>| -> *mut NSEvent {
        let e = unsafe { ev.as_ref() };
        let mods = { e.modifierFlags() } & MODS;
        if { e.keyCode() } == 53 && mods.is_empty() {
            f();
        }
        ev.as_ptr()
    });
    unsafe { NSEvent::addLocalMonitorForEventsMatchingMask_handler(NSEventMask::KeyDown, &block) }
}

/// Swallow the next key press / lone modifier tap in this app and report it as a hotkey string;
/// Esc alone reports None (cancel). Drop the returned handle to stop listening.
pub fn capture_hotkey(on_done: impl Fn(Option<String>) + 'static) -> Option<Retained<objc2::runtime::AnyObject>> {
    let armed = Cell::new(None::<u16>);
    let block = RcBlock::new(move |ev: NonNull<NSEvent>| -> *mut NSEvent {
        let ev = unsafe { ev.as_ref() };
        let (ty, code, flags) = { (ev.r#type(), ev.keyCode(), ev.modifierFlags()) };
        if ty == NSEventType::FlagsChanged {
            match MOD_TAPS.iter().find(|m| m.1 == code) {
                Some(&(_, _, f)) if flags.contains(f) => armed.set(Some(code)),
                Some(&(name, ..)) if armed.get() == Some(code) => {
                    armed.set(None);
                    on_done(Some(name.into()));
                }
                _ => armed.set(None),
            }
        } else {
            armed.set(None);
            let mods = flags & MODS;
            if code == 53 && mods.is_empty() {
                on_done(None);
            } else if let Some(n) = chord_name(code, mods) {
                on_done(Some(n));
            }
        }
        std::ptr::null_mut()
    });
    unsafe {
        NSEvent::addLocalMonitorForEventsMatchingMask_handler(NSEventMask::KeyDown | NSEventMask::FlagsChanged, &block)
    }
}

/// Install global + local NSEvent monitors; `on_fire` runs on the main thread. Keep the returned handles alive.
pub fn install_hotkey(hotkey: Hotkey, on_fire: impl Fn() + 'static) -> Vec<Retained<objc2::runtime::AnyObject>> {
    let on_fire = Rc::new(on_fire);
    let armed = Rc::new(Cell::new(false)); // modifier currently held with no other key pressed
    let handler = move |ev: NonNull<NSEvent>| {
        let ev = unsafe { ev.as_ref() };
        let (ty, code, flags) = { (ev.r#type(), ev.keyCode(), ev.modifierFlags()) };
        match &hotkey {
            Hotkey::ModifierTap { keycode, flag } => {
                if ty == NSEventType::FlagsChanged && code == *keycode {
                    if flags.contains(*flag) {
                        armed.set(true);
                    } else if armed.replace(false) {
                        on_fire();
                    }
                } else if ty == NSEventType::KeyDown || ty == NSEventType::FlagsChanged {
                    armed.set(false);
                }
            }
            Hotkey::Chord { mods, keycode } => {
                if ty == NSEventType::KeyDown && code == *keycode && (flags & MODS) == *mods {
                    on_fire();
                }
            }
        }
    };
    let h2 = handler.clone();
    let mask = NSEventMask::KeyDown | NSEventMask::FlagsChanged;
    let global = RcBlock::new(move |ev: NonNull<NSEvent>| handler(ev));
    let local = RcBlock::new(move |ev: NonNull<NSEvent>| -> *mut NSEvent {
        h2(ev);
        ev.as_ptr()
    });
    let mut handles = Vec::new();
    unsafe {
        if let Some(g) = NSEvent::addGlobalMonitorForEventsMatchingMask_handler(mask, &global) {
            handles.push(g);
        }
        if let Some(l) = NSEvent::addLocalMonitorForEventsMatchingMask_handler(mask, &local) {
            handles.push(l);
        }
    }
    handles
}

/// Put a dark-tinted Liquid Glass view (macOS 26+) behind egui's view; egui then paints on a transparent panel.
/// Sits in the window's frame view below the content view, because wgpu's Metal layer would draw under any subview.
fn add_glass(win: &objc2_app_kit::NSWindow) -> bool {
    use objc2::MainThreadOnly;
    use objc2_app_kit::{NSAutoresizingMaskOptions, NSColor, NSGlassEffectView, NSWindowOrderingMode};
    if objc2::runtime::AnyClass::get(c"NSGlassEffectView").is_none() {
        return false;
    } // older macOS: keep the opaque panel
    let (Some(mtm), Some(content)) = (MainThreadMarker::new(), win.contentView()) else {
        return false;
    };
    let Some(frame_view) = (unsafe { content.superview() }) else {
        return false;
    };
    let glass = NSGlassEffectView::initWithFrame(NSGlassEffectView::alloc(mtm), content.frame());
    glass.setCornerRadius(16.0);
    glass.setTintColor(Some(&NSColor::colorWithSRGBRed_green_blue_alpha(
        30.0 / 255.0,
        30.0 / 255.0,
        46.0 / 255.0,
        0.6,
    ))); // Catppuccin Mocha base (theme::BASE); mostly opaque, slight see-through
    glass.setAutoresizingMask(
        NSAutoresizingMaskOptions::ViewWidthSizable | NSAutoresizingMaskOptions::ViewHeightSizable,
    );
    frame_view.addSubview_positioned_relativeTo(&glass, NSWindowOrderingMode::Below, Some(&content));
    true
}

/// Direct control of the popup NSWindow, usable from the hotkey/menu callbacks even while the window is hidden.
pub struct Popup(
    Retained<objc2_app_kit::NSWindow>,
    pub bool,   /* has Liquid Glass backdrop */
    Cell<bool>, /* show() called, not hidden since */
);
impl Popup {
    pub fn from_handle(h: &dyn raw_window_handle::HasWindowHandle) -> Option<Self> {
        let raw_window_handle::RawWindowHandle::AppKit(h) = h.window_handle().ok()?.as_raw() else {
            return None;
        };
        let view: &objc2_app_kit::NSView = unsafe { h.ns_view.cast().as_ref() };
        let win = view.window()?;
        win.setLevel(objc2_app_kit::NSFloatingWindowLevel);
        win.setCollectionBehavior(
            objc2_app_kit::NSWindowCollectionBehavior::CanJoinAllSpaces
                | objc2_app_kit::NSWindowCollectionBehavior::FullScreenAuxiliary,
        );
        let glass = add_glass(&win);
        // "hidden" = transparent + click-through but still on screen: eframe skips ui() for a truly hidden root,
        // and Settings/onboarding are immediate viewports drawn from it (a hidden root made egui panic).
        win.setAlphaValue(0.0);
        win.setIgnoresMouseEvents(true);
        win.orderFrontRegardless();
        Some(Self(win, glass, Cell::new(false)))
    }
    /// Show centered horizontally on the main screen, near the bottom or top edge, and make it key.
    pub fn show(&self, at_top: bool) {
        let mtm = MainThreadMarker::new().expect("main thread");
        if let Some(screen) = objc2_app_kit::NSScreen::mainScreen(mtm) {
            let (sf, wf) = (screen.visibleFrame(), self.0.frame());
            let x = sf.origin.x + (sf.size.width - wf.size.width) / 2.0;
            let y = if at_top {
                sf.origin.y + sf.size.height - wf.size.height - 24.0
            } else {
                sf.origin.y + 48.0
            };
            self.0.setFrameOrigin(objc2_foundation::NSPoint::new(x, y));
        }
        self.0.setAlphaValue(1.0);
        self.0.setIgnoresMouseEvents(false);
        activate_app();
        self.0.makeKeyAndOrderFront(None);
        self.2.set(true);
    }
    /// Make the popup transparent and click-through, and hand focus back to `back_to` (the app the user was in).
    /// Cooperative activation (yield + activate) is what macOS 14+ honors; ignoring-other-apps is a no-op.
    pub fn hide(&self, back_to: Option<&NSRunningApplication>) {
        self.2.set(false);
        self.0.setAlphaValue(0.0);
        self.0.setIgnoresMouseEvents(true);
        let app = NSApplication::sharedApplication(MainThreadMarker::new().expect("main thread"));
        if !app.isActive() {
            return;
        }
        match back_to {
            Some(t) => {
                app.yieldActivationToApplication(t);
                t.activateWithOptions(NSApplicationActivationOptions::empty());
            }
            None => app.deactivate(),
        }
    }
    pub fn visible(&self) -> bool {
        self.2.get()
    }
    pub fn is_key(&self) -> bool {
        self.0.isKeyWindow()
    }
}

